// This platform's code for an allowed key, or nothing.
inline std::optional<unsigned short> key_code(const std::string &code) {
#ifdef __APPLE__
    const auto &keys = macos_key_codes();
#else
    const auto &keys = windows_key_codes();
#endif
    const auto found = keys.find(code);
    if (found == keys.end())
        return std::nullopt;
    return found->second;
}
